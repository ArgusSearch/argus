export function translate(language: "en" | "de", text: string): string {
  return language === "de" ? german[text] ?? text : text;
}

export function useText() {
  const { snapshot } = useOperatorSettings();
  const language = snapshot?.settings.appearance.language ?? "en";
  return (text: string) => translate(language, text);
}
